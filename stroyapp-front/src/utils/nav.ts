import { router, useFocusEffect, type Href } from 'expo-router';
import { useCallback, useRef, type RefObject } from 'react';

/** Сколько мс после открытия экрана повторное открытие считается дребезгом. */
const GUARD_MS = 600;

let lastAt = 0;

/**
 * Открыть экран — но не дважды от двойного нажатия.
 *
 * router.push не склеивает одинаковые переходы: быстрый двойной тап по
 * карточке кладёт в стек два экрана, и «Назад» приходится жать дважды. На
 * Android это воспроизводится легко — список остаётся нажимаемым, пока
 * идёт анимация перехода. Раньше от этого спасал navigation.navigate,
 * который одинаковые переходы склеивал сам.
 *
 * Защита по времени, а не флагом «занято»: флаг пришлось бы где-то
 * сбрасывать, и при несостоявшемся переходе он залипал бы навсегда.
 */
export function pushOnce(href: Href): void {
  const now = Date.now();
  if (now - lastAt < GUARD_MS) return;
  lastAt = now;
  router.push(href);
}

/**
 * Перед глазами ли экран: true, пока он в фокусе — верхний в стеке и на
 * открытой вкладке.
 *
 * Ответ на запрос приходит позже нажатия, и за это время человек может уйти
 * назад или открыть другой экран. Переход или окно с ошибкой из такого ответа
 * выскочили бы уже поверх чужого экрана — перед ними проверяем ref.current.
 * Ref, а не состояние: проверка идёт внутри уже запущенного async-обработчика,
 * и значение нужно на момент ответа, а не на момент нажатия.
 *
 * Шторки (вход, выбор даты) и просмотр фото — не экраны: с ними фокус
 * остаётся на экране под ними, и ref остаётся true.
 */
export function useOnTop(): RefObject<boolean> {
  const onTop = useRef(true);
  useFocusEffect(
    useCallback(() => {
      onTop.current = true;
      return () => {
        onTop.current = false;
      };
    }, []),
  );
  return onTop;
}
