def _compiled(patterns: List[str]) -> 're.Pattern[str]':
    # Слово — от края до края. Второе условие — только ради скорости: с
    # места, где стоит не буква (и не «6» из «6ля»), слово начаться не может,
    # и перебирать там все правила незачем. На тексте из одних точек и
    # пробелов это разница в десятки раз.
    return re.compile(
        rf'(?<!{_LETTER})(?=[а-яәіңғүұқөһa-z6])(?:' + '|'.join(f'(?:{p})' for p in patterns) + rf')(?!{_LETTER})'
    )


_BAD = _compiled(_RU + _KZ + _TRANSLIT + _EN)
_BAD_RU_ONLY = _compiled(_RU_ONLY)


def _skipped_places(text: str) -> FrozenSet[int]:
    """Места знаков, которых в слове не видно (см. _SKIPPED_CATEGORIES)."""
    if text.isascii():
        return frozenset()
    return frozenset(
        index for index, char in enumerate(text)
        if char >= _FIRST_SKIPPED and unicodedata.category(char) in _SKIPPED_CATEGORIES
    )


def _readings(text: str, skipped: FrozenSet[int]) -> List[Dict[int, str]]:
    """
    Как ещё можно прочесть текст: для каждого прочтения — {место: буква}, какие
    знаки считать русскими буквами. Первое прочтение — как написано (пустое).
    Остальные появляются, только если в тексте есть слова, где русские буквы
    стоят вперемешку с латинскими или цифрами.
    """
    # Невидимый знак слово не делит: для разбивки на слова все они — один и
    # тот же знак, который входит в _TOKEN. Места в тексте при этом те же.
    plain = text
    if skipped:
        plain = ''.join(_ZERO_WIDTH if index in skipped else char for index, char in enumerate(text))
    by_look: Dict[int, str] = {}
    by_kazakh: Dict[int, str] = {}
    by_sound: Dict[int, str] = {}
    for token in _TOKEN.finditer(plain):
        word = token.group()
        cyrillic = len(_CYRILLIC.findall(word))
        if not cyrillic:
            continue
        for offset, char in enumerate(word):
            place = token.start() + offset
            if char in _DIGITS:
                if cyrillic >= 3:
                    by_look[place] = by_kazakh[place] = by_sound[place] = _DIGITS[char]
                continue
            if char in _BY_LOOK:
                by_look[place] = _BY_LOOK[char]
                by_kazakh[place] = _KAZAKH_I if char in 'iI' else _BY_LOOK[char]
            low = char.lower()
            if cyrillic >= 2 and low in _BY_SOUND:
                by_sound[place] = _BY_SOUND[low]
    # Прочтение с казахской «і» отличается от прочтения «на вид», только если
    # латинская «i» в таком слове есть, — иначе оно отсеется как повтор.
    readings: List[Dict[int, str]] = [{}]
    for extra in (by_look, by_kazakh, by_sound):
        if extra and extra not in readings:
            readings.append(extra)
    return readings


def _normalize(text: str, swapped: Dict[int, str], skipped: FrozenSet[int],
               squeeze: bool = False, keep: int = 1) -> Tuple[str, List[int], List[int], bool]:
    """
    Текст в виде для сравнения и карта обратно: знак i приведённого текста —
    это отрезок исходного от starts[i] до ends[i] (конец не включён). Четвёртым
    возвращается, встретились ли три одинаковые буквы подряд.

    swapped — какие знаки читать как русские буквы (см. _readings).
    skipped — места знаков, которых в слове не видно (см. _skipped_places).
    squeeze — считать за одну уже две одинаковые русские буквы подряд, а не
    три: «суука» читается как «сука». Отдельным прочтением, потому что у
    обычных слов удвоение значимо («ссать», «ниггер»).
    keep — сколько букв остаётся от трёх и больше одинаковых подряд: одна
    («бляяя» — «бля») или две («сссать» — «ссать»).
    """
    out: List[str] = []
    starts: List[int] = []
    ends: List[int] = []
    run = 0   # сколько раз подряд уже встретилась последняя буква
    long_run = False
    for index, char in enumerate(text):
        if index in skipped:
            # Невидимый знак или значок над буквой: относим его к предыдущей
            # букве, чтобы звёздочки закрыли и его. «и» с краткой — это «й»;
            # «е» с двумя точками — «ё», а она и так читается как «е».
            if ends:
                ends[-1] = index + 1
                if char == _BREVE and out[-1] == 'и':
                    out[-1] = 'й'
            continue
        low = swapped.get(index) or char.lower()[:1]
        if low == 'ё':
            low = 'е'
        if out and low == out[-1] and low.isalpha():
            run += 1
            if squeeze and low in _SQUEEZED:
                # Вторая и следующие такие же буквы: отрезок первой
                # растягивается до конца череды.
                ends[-1] = index + 1
                continue
            if run >= 3:
                # Лишняя одинаковая буква подряд: «бляяя» — это «бля». Первые
                # две уже записаны: если остаться должна одна, вторую убираем.
                # Отрезок последней оставшейся растягивается до конца череды.
                long_run = True
                if run == 3 and keep == 1:
                    out.pop()
                    starts.pop()
                    ends.pop()
                ends[-1] = index + 1
                continue
        else:
            run = 1
        out.append(low)
        starts.append(index)
        ends.append(index + 1)
    return ''.join(out), starts, ends, long_run


def spans(text: str) -> List[Tuple[int, int]]:
    """Отрезки исходного текста, занятые бранью: [(начало, конец), …]."""
    if not text:
        return []
    skipped = _skipped_places(text)
    patterns = (_BAD,) if _KAZAKH.search(text) else (_BAD, _BAD_RU_ONLY)
    found = set()
    for reading in _readings(text, skipped):
        normal, starts, ends, long_run = _normalize(text, reading, skipped)
        variants = [(normal, starts, ends), _normalize(text, reading, skipped, squeeze=True)[:3]]
        if long_run:
            # Растянутое слово, где удвоенная буква — своя: «сссать», «ниггггер».
            # От череды остаются две буквы, а не одна. Только когда такая череда
            # в тексте есть: это ещё два прохода по нему.
            variants.append(_normalize(text, reading, skipped, keep=2)[:3])
            variants.append(_normalize(text, reading, skipped, squeeze=True, keep=2)[:3])
        for normal, starts, ends in variants:
            for pattern in patterns:
                found.update((starts[m.start()], ends[m.end() - 1]) for m in pattern.finditer(normal))
    # Прочтения могут найти одно и то же слово с разными краями — сливаем.
    merged: List[Tuple[int, int]] = []
    for start, end in sorted(found):
        if merged and start < merged[-1][1]:
            merged[-1] = (merged[-1][0], max(merged[-1][1], end))
        else:
            merged.append((start, end))
    return merged


def hide(text: str) -> str:
    """Тот же текст, где брань закрыта звёздочками. Длина текста не меняется."""
    found = spans(text)
    if not found:
        return text
    chars = list(text)
    for start, end in found:
        chars[start:end] = '*' * (end - start)
    return ''.join(chars)


def _field(text: str) -> str:
    # Сначала то, что не дойдёт до базы (нулевой байт, «половинка» суррогатной
    # пары): слово с таким знаком внутри фильтр иначе не узнал бы.
    text = clean_text(text)
    # Свои проверки длины у полей идут после этого типа. Без отказа здесь
    # текст в мегабайты сначала читался бы фильтром — секунды работы на запрос.
    if len(text) > MAX_LENGTH:
        raise ValueError('Текст слишком длинный')
    return hide(text)


