import { Platform } from 'react-native';

/**
 * Можно ли оплачивать тариф прямо из приложения.
 *
 * На iOS — нет: подписку на цифровую услугу App Store разрешает продавать
 * только встроенными покупками, а оплата картой в браузере — повод
 * отклонить приложение. Поэтому на iPhone нет ни кнопки оплаты, ни цен, ни
 * ссылки на оплату: только слова о том, что Pro оформляется в веб-кабинете.
 * На Android и в вебе оплата картой остаётся.
 */
export const PAY_IN_APP = Platform.OS !== 'ios';
